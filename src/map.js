    if (e.kind === 'boss' || e.carrier) continue;                      // el jefe y los portadores de máscara no cambian
    const r = rnd();
    let act = e.kind === 'runner' ? 'patrol' : e.kind === 'heavy' ? (r < 0.6 ? 'watch' : 'patrol') : r < 0.42 ? 'patrol' : r < 0.68 ? 'watch' : r < 0.86 ? 'smoke' : 'sit';
